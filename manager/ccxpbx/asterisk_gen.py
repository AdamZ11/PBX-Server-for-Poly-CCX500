"""Generates the Asterisk include files in /etc/asterisk/ccxpbx/.

The static configs in /etc/asterisk (shipped in asterisk/ of this repo) #include these.
"""
import os
import tempfile
from pathlib import Path

from . import config, plan

HEADER = "; Generated by ccxpbx - DO NOT EDIT, changes are overwritten.\n"
TRANSPORT_FILE = "pjsip_transports.conf"


def esc(value) -> str:
    """Escape a value for an Asterisk .conf file."""
    return str(value).replace("\r", "").replace("\n", " ").replace(";", r"\;")


def _section(name: str, items: list[tuple[str, str]]) -> str:
    lines = [f"[{name}]"] + [f"{k}={esc(v)}" for k, v in items if v is not None and v != ""]
    return "\n".join(lines) + "\n"


def gen_transports(s: dict) -> str:
    common = []
    for net in [n.strip() for n in s.get("local_net", "").split(",") if n.strip()]:
        common.append(("local_net", net))
    if s.get("external_ip"):
        common += [("external_media_address", s["external_ip"]), ("external_signaling_address", s["external_ip"])]
    out = [HEADER]
    out.append(_section("transport-udp", [("type", "transport"), ("protocol", "udp"),
                                          ("bind", f"0.0.0.0:{s['sip_port']}"), ("tos", "cs3"), ("cos", "3")] + common))
    out.append(_section("transport-tcp", [("type", "transport"), ("protocol", "tcp"),
                                          ("bind", f"0.0.0.0:{s['sip_port']}"), ("tos", "cs3"), ("cos", "3")] + common))
    if s.get("sip_transport") == "tls":
        out.append(_section("transport-tls", [
            ("type", "transport"), ("protocol", "tls"), ("bind", f"0.0.0.0:{s['tls_port']}"),
            ("cert_file", config.TLS_CERT), ("priv_key_file", config.TLS_KEY),
            ("method", "tlsv1_2"), ("tos", "cs3"), ("cos", "3"),
        ] + common))
    return "\n".join(out)


def gen_endpoints(snap: dict) -> str:
    s = snap["settings"]
    codecs = ",".join(c.strip() for c in s.get("codecs", "g722,alaw,ulaw").split(",") if c.strip())
    tls = s.get("sip_transport") == "tls"
    out = [HEADER]
    for e in snap["extensions"]:
        ext = e["ext"]
        name = plan.clean_text(e["name"])
        out.append(_section(ext, [
            ("type", "endpoint"),
            ("context", "from-internal"),
            ("subscribe_context", "from-internal"),
            ("disallow", "all"),
            ("allow", codecs),
            ("auth", ext),
            ("aors", ext),
            ("callerid", f'"{name}" <{ext}>'),
            ("mailboxes", f"{ext}@default" if e["vm_enabled"] else ""),
            ("named_call_group", e["pickup_group"]),
            ("named_pickup_group", e["pickup_group"]),
            ("direct_media", "no"),
            ("rtp_symmetric", "yes"),
            ("force_rport", "yes"),
            ("rewrite_contact", "yes"),
            ("dtmf_mode", "rfc4733"),
            ("send_pai", "yes"),
            ("trust_id_inbound", "yes"),
            ("trust_id_outbound", "yes"),
            ("tone_zone", s.get("tone_zone", "")),
            ("device_state_busy_at", ""),
            ("allow_subscribe", "yes"),
            ("transport", "transport-tls" if tls else ""),
            ("media_encryption", "sdes" if tls else ""),
            ("tos_audio", "ef"),
            ("cos_audio", "5"),
        ]))
        out.append(_section(ext, [("type", "auth"), ("auth_type", "userpass"),
                                  ("username", ext), ("password", e["secret"])]))
        out.append(_section(ext, [("type", "aor"), ("max_contacts", str(e["max_contacts"])),
                                  ("remove_existing", "yes"), ("qualify_frequency", "60"),
                                  ("minimum_expiration", "60")]))
    return "\n".join(out)


def gen_trunks(snap: dict) -> str:
    out = [HEADER]
    for t in snap["trunks"]:
        n = t["name"]
        hostport = f"{t['host']}:{t['port']}"
        has_auth = bool(t["username"])
        if has_auth:
            out.append(_section(f"{n}-auth", [("type", "auth"), ("auth_type", "userpass"),
                                              ("username", t["username"]), ("password", t["password"])]))
        if t["register"] and has_auth:
            out.append(_section(f"{n}-reg", [
                ("type", "registration"), ("transport", "transport-udp"),
                ("outbound_auth", f"{n}-auth"), ("server_uri", f"sip:{hostport}"),
                ("client_uri", f"sip:{t['username']}@{t['host']}"), ("contact_user", t["username"]),
                ("retry_interval", "60"), ("forbidden_retry_interval", "600"), ("expiration", "3600"),
                ("line", "yes"), ("endpoint", n),
            ]))
        out.append(_section(n, [("type", "aor"), ("contact", f"sip:{hostport}"), ("qualify_frequency", "60")]))
        out.append(_section(n, [
            ("type", "endpoint"), ("transport", "transport-udp"), ("context", "from-trunk"),
            ("disallow", "all"), ("allow", t["codecs"] or "alaw,ulaw"),
            ("outbound_auth", f"{n}-auth" if has_auth else ""), ("aors", n),
            ("from_user", t["from_user"] or t["username"]), ("from_domain", t["from_domain"]),
            ("direct_media", "no"), ("rtp_symmetric", "yes"), ("force_rport", "yes"),
            ("rewrite_contact", "yes"), ("dtmf_mode", "rfc4733"), ("send_rpid", "yes"),
            ("tone_zone", snap["settings"].get("tone_zone", "")),
        ]))
        out.append(_section(f"{n}-identify", [("type", "identify"), ("endpoint", n), ("match", t["host"])]))
    return "\n".join(out)


def _dest_goto(dest: str) -> str:
    if dest.startswith("vm:"):
        return f"VoiceMail({dest[3:]}@default,u)"
    return f"Goto(from-internal,{dest},1)"


def gen_dialplan(snap: dict) -> str:
    out = [HEADER]

    out.append("[ccx-extensions]")
    for e in snap["extensions"]:
        ext = e["ext"]
        out.append(f"exten => {ext},hint,PJSIP/{ext}")
        out.append(f"exten => {ext},1,Gosub(sub-dial-ext,s,1({ext},{e['ring_time']},{e['vm_enabled']},{e['record']}))")
        out.append(" same => n,Hangup()")
    out.append("")

    out.append("[ccx-ringgroups]")
    for g in snap["ring_groups"]:
        members = [m for m in g["members"].split(",") if m]
        num = g["num"]
        out.append(f"exten => {num},1,NoOp(Ring group {plan.clean_text(g['name'])})")
        out.append(f" same => n,Set(__PICKUPMARK={num})")
        out.append(f" same => n,Set(CALLERID(name)={plan.clean_text(g['name'], 16)}: ${{CALLERID(name)}})")
        if members:
            if g["strategy"] == "hunt":
                for m in members:
                    out.append(f" same => n,Dial(Local/{m}@ccx-ringtarget,{g['ring_time']},tTkK)")
                    out.append(' same => n,ExecIf($["${DIALSTATUS}"="ANSWER"]?Hangup())')
            else:
                dial = "&".join(f"Local/{m}@ccx-ringtarget" for m in members)
                out.append(f" same => n,Dial({dial},{g['ring_time']},tTkK)")
                out.append(' same => n,ExecIf($["${DIALSTATUS}"="ANSWER"]?Hangup())')
        out.append(f" same => n,{_dest_goto(g['failover'])}" if g["failover"] else " same => n,Hangup()")
    out.append("")

    out.append("[ccx-outbound]")
    for r in snap["outbound"]:
        pattern = r["pattern"]
        number = f"{r['prepend']}${{EXTEN:{r['strip']}}}" if r["strip"] else f"{r['prepend']}${{EXTEN}}"
        trunk = next((t for t in snap["trunks"] if t["name"] == r["trunk"]), None)
        cid = trunk["callerid"] if trunk else ""
        out.append(f"exten => {pattern},1,Gosub(sub-outbound,s,1({r['trunk']},{number},{cid}))")
        out.append(" same => n,Hangup()")
    out.append("")

    out.append("[ccx-inbound]")
    for r in snap["inbound"]:
        out.append(f"exten => {r['did']},1,{_dest_goto(r['destination'])}")
    default = snap["settings"].get("inbound_default", "")
    if default:
        out.append(f"exten => _[+0-9].,1,{_dest_goto(default)}")
        out.append(f"exten => s,1,{_dest_goto(default)}")
    out.append("")
    return "\n".join(out)


def gen_globals(snap: dict) -> str:
    page = "&".join(f"PJSIP/{e['ext']}" for e in snap["extensions"] if e["page_member"])
    return HEADER + "\n".join([
        f"PAGE_ALL={page}",
        f"INTERCOM_ALERT={plan.INTERCOM_ALERT}",
        f"TZ_NAME={snap['settings'].get('timezone_name', 'UTC')}",
    ]) + "\n"


def gen_voicemail(snap: dict) -> str:
    tz = "local"
    tzname = snap["settings"].get("timezone_name") or "UTC"
    out = [HEADER, "[zonemessages]", f"{tz}={tzname}|'vm-received' Q 'digits/at' HM", "", "[default]"]
    for e in snap["extensions"]:
        if not e["vm_enabled"]:
            continue
        opts = [f"tz={tz}"]
        if e["email"]:
            opts.append("attach=yes")
        out.append(f"{e['ext']} => {e['vm_pin'] or '0000'},{plan.clean_text(e['name'])},"
                   f"{plan.clean_text(e['email'], 128)},,{'|'.join(opts)}")
    return "\n".join(out) + "\n"


def generate(snap: dict) -> dict[str, str]:
    return {
        TRANSPORT_FILE: gen_transports(snap["settings"]),
        "pjsip_endpoints.conf": gen_endpoints(snap),
        "pjsip_trunks.conf": gen_trunks(snap),
        "extensions_generated.conf": gen_dialplan(snap),
        "globals.conf": gen_globals(snap),
        "voicemail_boxes.conf": gen_voicemail(snap),
    }


def write_files(files: dict[str, str], directory: Path | None = None) -> list[str]:
    """Atomically write files, return the names whose content changed."""
    directory = Path(directory or config.AST_GEN_DIR)
    directory.mkdir(parents=True, exist_ok=True)
    changed = []
    for name, content in files.items():
        target = directory / name
        try:
            if target.read_text() == content:
                continue
        except OSError:
            pass
        fd, tmp = tempfile.mkstemp(dir=directory, prefix=".tmp-")
        with os.fdopen(fd, "w", newline="\n") as fh:
            fh.write(content)
        os.chmod(tmp, 0o640)
        os.replace(tmp, target)
        changed.append(name)
    return changed
